#!/usr/bin/env bash
# Regenerates src/main/kotlin/parity/RepositoryDcfHelpers.kt from the Android repository,
# so the driver builds terminal/unavailable DCF states with the app's own code.
set -euo pipefail
cd "$(dirname "$0")/../.."
R=apps/android/app/src/main/kotlin/com/discountscreener/android/data/repository/DefaultDashboardRepository.kt
OUT=tools/android-jvm-parity/src/main/kotlin/parity/RepositoryDcfHelpers.kt
start=$(grep -n '    private fun analysisFromSelection(' "$R" | cut -d: -f1)
fp=$(grep -n '    private fun notEligibleDecisionFingerprint(' "$R" | cut -d: -f1)
end=$((fp + 3))
{
  echo "// GENERATED by tools/android-jvm-parity/extract_helpers.sh from"
  echo "// apps/android/app/.../DefaultDashboardRepository.kt (analysisFromSelection .. notEligibleDecisionFingerprint),"
  echo "// verbatim except 'private fun' -> 'internal fun' at top level. Re-run the script after the source changes."
  echo "package parity"
  echo
  grep '^import com.discountscreener.core\|^import kotlin\|^import java' "$R"
  echo
  sed -n "${start},${end}p" "$R" | sed 's/^    //; s/^private fun/internal fun/'
} > "$OUT"
echo "wrote $OUT (lines $start-$end)"
